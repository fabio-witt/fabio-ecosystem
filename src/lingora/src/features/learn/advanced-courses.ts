import type { CefrLevel, Exercise, Lesson } from './catalog';

type AdvancedUnit = {
  title: string;
  level: Extract<CefrLevel, 'C1' | 'C2'>;
  lessons: Lesson[];
};

function lesson(
  id: string, title: string, rule: string, structure: string,
  examples: Lesson['examples'], tip: string, ...ex: Exercise[]
): Lesson {
  return { id, title, rule, structure, examples, tip, ex };
}

function choice(prompt: string, options: string[], answer: number, explain: string): Exercise {
  return { type: 'choice', prompt, options, answer, explain };
}

function type(prompt: string, answer: string, explain: string): Exercise {
  return { type: 'type', prompt, accept: [answer], explain };
}

